-- ============================================================================
-- 文章全局唯一 uid：作为云端同步的业务键，替代原先的标题键
-- ============================================================================
-- 执行方式：Supabase Dashboard → SQL Editor → New query → 粘贴本文件全部内容 → Run
-- 本迁移幂等，可重复执行；不会删除已有数据。
--
-- 背景：旧版以 title 为业务键，改名会被同步视为「删旧文 + 增新文」导致文章复制；
--       同名文章也会互相串数据。uid 在文章创建时生成、终身不变。
-- 说明：开发阶段执行本迁移时已清空旧数据（truncate），uid 为可空列，
--       同步侧会对异常缺 uid 的记录自动生成并回写。
-- ============================================================================

alter table public.articles
  add column if not exists "uid" text;

create index if not exists idx_articles_username_uid
  on public.articles (username, "uid");
